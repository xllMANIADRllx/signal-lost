// ═══ SAVE SYSTEM ═══
const Save = {
  get(k, d) { try { const v = localStorage.getItem('sl_' + k); return v !== null ? JSON.parse(v) : d; } catch { return d; } },
  set(k, v) { try { localStorage.setItem('sl_' + k, JSON.stringify(v)); } catch {} },
  hs() { return this.get('hs', 0); },
  saveHs(s) { if (s > this.hs()) this.set('hs', s); },
  shards() { return this.get('shards', 0); },
  addShards(n) { this.set('shards', this.shards() + n); },
  spendShards(n) { const s = this.shards(); if (s < n) return false; this.set('shards', s - n); return true; },
  isOwned(id) { return !!(this.get('owned', {})[id]); },
  own(id) { const o = this.get('owned', {}); o[id] = true; this.set('owned', o); },
  skin() { return this.get('skin', 'ranger'); },
  setSkin(s) { this.set('skin', s); },
  lb() { return this.get('lb', []); },
  addLb(e) { const lb = this.lb(); lb.push(e); lb.sort((a, b) => b.score - a.score); lb.splice(10); this.set('lb', lb); },
  lore() { return this.get('lore', []); },
  unlockLore(i) { const l = this.lore(); if (!l.includes(i)) { l.push(i); this.set('lore', l); } },
  meta(k, d) { return (this.get('meta', {}))[k] ?? d; },
  setMeta(k, v) { const m = this.get('meta', {}); m[k] = v; this.set('meta', m); },
  fragments() { return this.get('fragments', 0); },
  addFragments(n) { this.set('fragments', this.fragments() + n); },
  spendFragments(n) { const f = this.fragments(); if (f < n) return false; this.set('fragments', f - n); return true; },
  hasMeta(k) { return !!this.meta(k, false); },
};
